test('自校验解码：1 / 17 / 44 / 120 / 213 字节跨版本往返', () => {
  // byte 模式容量 = 数据码字位宽 - 模式指示符 4 bit - 字符计数 8/16 bit：v1=14、v2=26、v4=62、v7=122、v10=213
  const cases: { length: number; version: number }[] = [
    { length: 1, version: 1 },
    { length: 17, version: 2 },
    { length: 44, version: 4 },
    { length: 120, version: 7 },
    { length: 213, version: 10 },
  ];
  const covered = new Set<number>();
  for (const { length, version } of cases) {
    const content = asciiOfLength(length);
    const matrix = encodeQrMatrix(content);
    assert.equal(matrix.size, version * 4 + 17, `${length} 字节应选版本 ${version}`);
    const decoded = decodeMatrix(matrix);
    assert.equal(decoded.version, version);
    assert.equal(decoded.dataBytes.length, length);
    assert.deepEqual(decoded.dataBytes, [...new TextEncoder().encode(content)]);
    covered.add(decoded.version);
  }
  assert.deepEqual([...covered].sort((a, b) => a - b), [1, 2, 4, 7, 10]);
});

test('自校验解码：UTF-8 多字节内容按字节计数', () => {
  const content = '扫码登录：商汤小浣熊（Raccoon）';
  const byteLength = new TextEncoder().encode(content).length;
  assert.ok(byteLength > content.length, '该用例必须包含多字节字符');
  const decoded = decodeMatrix(encodeQrMatrix(content));
  assert.deepEqual(decoded.dataBytes, [...new TextEncoder().encode(content)]);
});

test('自校验解码：每个版本都能自洽读回', () => {
  for (let version = 1; version <= 10; version += 1) {
    const capacity = dataCapacityBytes(version);
    const content = asciiOfLength(capacity);
    const matrix = encodeQrMatrix(content);
    assert.equal(matrix.size, version * 4 + 17);
    const decoded = decodeMatrix(matrix);
    assert.equal(decoded.version, version);
    assert.deepEqual(decoded.dataBytes, [...new TextEncoder().encode(content)]);
    assert.ok(decoded.ecBlocks >= 1);
  }
});

test('版本选择：短串 v1、200 字节 v10、214 字节抛错', () => {
  assert.equal(encodeQrMatrix('a').size, 21);
  assert.equal(encodeQrMatrix(asciiOfLength(14)).size, 21);
  assert.equal(encodeQrMatrix(asciiOfLength(15)).size, 25);
  assert.equal(encodeQrMatrix(asciiOfLength(200)).size, 57);
  assert.equal(encodeQrMatrix(asciiOfLength(213)).size, 57);
  assert.throws(() => encodeQrMatrix(asciiOfLength(214)), RangeError);
  assert.throws(() => encodeQrMatrix('长'.repeat(72)), RangeError);
});

test('SVG 结构：标签、viewBox、默认尺寸与 path 数量', () => {
  const content = 'https://xiaohuanxiong.com/login/mp?scene=abc';
  const { size, modules } = encodeQrMatrix(content);
  const svg = renderQrSvg(content);
  assert.ok(svg.startsWith('<svg '), 'SVG 必须以 <svg 开头');
  assert.ok(svg.endsWith('</svg>'), 'SVG 必须以 </svg> 结尾');
  assert.match(svg, new RegExp(`viewBox="0 0 ${size + 8} ${size + 8}"`));
  assert.match(svg, /width="220"/);
  assert.match(svg, /height="220"/);
  assert.match(svg, /shape-rendering="crispEdges"/);

  const darkCount = modules.flat().filter(Boolean).length;
  assert.equal((svg.match(/M/g) ?? []).length, darkCount, 'path 里的 M 个数必须等于深色模块数');

  const custom = renderQrSvg(content, { size: 320 });
  assert.match(custom, /width="320"/);
  assert.match(custom, /height="320"/);
  assert.throws(() => renderQrSvg(content, { size: 0 }), RangeError);
});

test('静区：四周 4 模块外扩后全浅色', () => {
  const content = 'https://xiaohuanxiong.com/login/mp?scene=quiet-zone';
  const { size, modules } = encodeQrMatrix(content);
  const svg = renderQrSvg(content);
  const extent = size + 8;

  // 用 path 里给出的模块坐标重建整幅图（坐标已含静区偏移），再检查边框
  const painted = Array.from({ length: extent }, () => new Array<boolean>(extent).fill(false));
  for (const match of svg.matchAll(/M(\d+) (\d+)h1v1h-1z/g)) {
    const x = Number(match[1]);
    const y = Number(match[2]);
    assert.ok(x >= 4 && x < 4 + size, `模块 x=${x} 落在静区内`);
    assert.ok(y >= 4 && y < 4 + size, `模块 y=${y} 落在静区内`);
    painted[y]![x] = true;
  }
  for (let i = 0; i < extent; i += 1) {
    for (let j = 0; j < extent; j += 1) {
      const inQuietZone = i < 4 || i >= extent - 4 || j < 4 || j >= extent - 4;
      if (inQuietZone) assert.equal(painted[i]?.[j], false, `静区模块 (${j},${i}) 不是浅色`);
    }
  }
  // 除静区外必须与原矩阵逐模块一致
  for (let row = 0; row < size; row += 1) {
    for (let col = 0; col < size; col += 1) {
      assert.equal(painted[row + 4]?.[col + 4], modules[row]?.[col] === true, `模块 (${col},${row}) 与矩阵不一致`);
    }
  }
});
