/**
 * 独立的二维码解码器：按 ISO/IEC 18004 逐模块读回编码器的产物。
 * 不 import 被测模块的任何内部实现，功能表与几何规则在这里重新写一遍，
 * 这样才能发现「编码与解码共用同一个错误假设」之外的问题。
 */

const ALIGNMENT_CENTERS: readonly (readonly number[])[] = [
  [],
  [6, 18],
  [6, 22],
  [6, 26],
  [6, 30],
  [6, 34],
  [6, 22, 38],
  [6, 24, 42],
  [6, 26, 46],
  [6, 28, 50],
];

/** 等级 M、版本 1–10 的分块表：[块数, 每块数据码字, 每块 EC 码字]。 */
const BLOCK_GROUPS: readonly (readonly [number, number, number][])[] = [
  [[1, 16, 10]],
  [[1, 28, 16]],
  [[1, 44, 26]],
  [[2, 32, 18]],
  [[2, 43, 24]],
  [[4, 27, 16]],
  [[4, 31, 18]],
  [[2, 38, 22], [2, 39, 22]],
  [[3, 36, 22], [2, 37, 22]],
  [[4, 43, 26], [1, 44, 26]],
];

const GF_EXP = new Uint8Array(512);
const GF_LOG = new Uint8Array(256);
for (let i = 0, value = 1; i < 255; i += 1) {
  GF_EXP[i] = value;
  GF_LOG[value] = i;
  value <<= 1;
  if (value & 0x100) value ^= 0x11d;
}
for (let i = 255; i < 512; i += 1) GF_EXP[i] = GF_EXP[i - 255]!;

function gfMul(a: number, b: number): number {
  if (a === 0 || b === 0) return 0;
  return GF_EXP[GF_LOG[a]! + GF_LOG[b]!]!;
}

function blockPlan(version: number): { count: number; data: number; ec: number }[] {
  const plan: { count: number; data: number; ec: number }[] = [];
  for (const [count, data, ec] of BLOCK_GROUPS[version - 1] ?? []) plan.push({ count, data, ec });
  return plan;
}

function codewordCount(version: number): number {
  let total = 0;
  for (const group of blockPlan(version)) total += group.count * (group.data + group.ec);
  return total;
}

function dataCapacityBytes(version: number): number {
  let dataCodewords = 0;
  for (const group of blockPlan(version)) dataCodewords += group.count * group.data;
  return Math.floor((dataCodewords * 8 - 4 - (version < 10 ? 8 : 16)) / 8);
}

/** 标出所有功能图案模块；数据区即其余模块。 */
function buildReserved(version: number): boolean[][] {
  const size = version * 4 + 17;
  const reserved = Array.from({ length: size }, () => new Array<boolean>(size).fill(false));
  const mark = (col: number, row: number): void => {
    if (row >= 0 && row < size && col >= 0 && col < size) reserved[row]![col] = true;
  };

  for (const [cx, cy] of [[3, 3], [size - 4, 3], [3, size - 4]] as const) {
    for (let dy = -4; dy <= 4; dy += 1) for (let dx = -4; dx <= 4; dx += 1) mark(cx + dx, cy + dy);
  }
  for (let i = 0; i < size; i += 1) {
    mark(6, i);
    mark(i, 6);
  }
  const centers = ALIGNMENT_CENTERS[version - 1] ?? [];
  for (const cy of centers) {
    for (const cx of centers) {
      const corner =
        (cx === 6 && cy === 6) || (cx === 6 && cy === size - 7) || (cx === size - 7 && cy === 6);
      if (corner) continue;
      for (let dy = -2; dy <= 2; dy += 1) for (let dx = -2; dx <= 2; dx += 1) mark(cx + dx, cy + dy);
    }
  }
  for (let i = 0; i <= 5; i += 1) mark(8, i);
  mark(8, 7);
  mark(8, 8);
  mark(7, 8);
  for (let i = 9; i < 15; i += 1) mark(14 - i, 8);
  for (let i = 0; i < 8; i += 1) mark(size - 1 - i, 8);
  for (let i = 8; i < 15; i += 1) mark(8, size - 15 + i);
  mark(8, size - 8);
  if (version >= 7) {
    for (let i = 0; i < 18; i += 1) {
      const a = size - 11 + (i % 3);
      const b = Math.floor(i / 3);
      mark(a, b);
      mark(b, a);
    }
  }
  return reserved;
}

function bitAt(modules: readonly (readonly boolean[])[], col: number, row: number): number {
  return modules[row]?.[col] === true ? 1 : 0;
}

function bchRemainder(value: number, degree: number, generator: number): number {
  let remainder = value;
  for (let i = 0; i < degree; i += 1) remainder = (remainder << 1) ^ ((remainder >>> (degree - 1)) * generator);
  return remainder;
}

interface DecodedQr {
  version: number;
  mask: number;
  dataBytes: number[];
  ecBlocks: number;
}

/**
 * 逐模块校验功能图案：定位图案（含分隔符）、时序图案、对齐图案、暗模块。
 * 数据区被掩码后看不出图案，所以这一步必须在去掩码之前、只看功能模块。
 */
function assertFunctionPatterns(matrix: { size: number; modules: boolean[][] }): void {
  const { size, modules } = matrix;
  const version = (size - 17) / 4;
  const dark = (col: number, row: number): boolean => modules[row]?.[col] === true;

  for (const [cx, cy] of [[3, 3], [size - 4, 3], [3, size - 4]] as const) {
    for (let dy = -4; dy <= 4; dy += 1) {
      for (let dx = -4; dx <= 4; dx += 1) {
        const col = cx + dx;
        const row = cy + dy;
        if (col < 0 || row < 0 || col >= size || row >= size) continue;
        const distance = Math.max(Math.abs(dx), Math.abs(dy));
        assert.equal(dark(col, row), distance !== 2 && distance !== 4, `定位图案 (${col},${row}) 颜色错误`);
      }
    }
  }

  // 时序图案只在两枚定位图案之间交替，两端各留 8 模块给定位图案与分隔符
  for (let i = 8; i < size - 8; i += 1) {
    assert.equal(dark(i, 6), i % 2 === 0, `横向时序图案 (${i},6) 颜色错误`);
    assert.equal(dark(6, i), i % 2 === 0, `纵向时序图案 (6,${i}) 颜色错误`);
  }

  for (const cy of ALIGNMENT_CENTERS[version - 1] ?? []) {
    for (const cx of ALIGNMENT_CENTERS[version - 1] ?? []) {
      if ((cx === 6 && cy === 6) || (cx === 6 && cy === size - 7) || (cx === size - 7 && cy === 6)) continue;
      for (let dy = -2; dy <= 2; dy += 1) {
        for (let dx = -2; dx <= 2; dx += 1) {
          assert.equal(
            dark(cx + dx, cy + dy),
            Math.max(Math.abs(dx), Math.abs(dy)) !== 1,
            `对齐图案 (${cx + dx},${cy + dy}) 颜色错误`,
          );
        }
      }
    }
  }

  assert.equal(dark(8, size - 8), true, '固定的暗模块必须为深色');
}

function decodeMatrix(matrix: { size: number; modules: boolean[][] }): DecodedQr {
  const { size, modules } = matrix;
  assert.equal((size - 17) % 4, 0, `矩阵边长 ${size} 不是 4n+17`);
  const version = (size - 17) / 4;
  assertFunctionPatterns(matrix);

  // 格式信息：两份必须一致，BCH(15,5) 校验必须通过，等级指示符必须是 M(00)
  const formatPositions: readonly (readonly [number, number])[] = [
    ...Array.from({ length: 6 }, (_, i) => [8, i] as const),
    [8, 7],
    [8, 8],
    [7, 8],
    ...Array.from({ length: 6 }, (_, i) => [14 - (i + 9), 8] as const),
  ];
  const secondaryPositions: readonly (readonly [number, number])[] = [
    ...Array.from({ length: 8 }, (_, i) => [size - 1 - i, 8] as const),
    ...Array.from({ length: 7 }, (_, i) => [8, size - 15 + (i + 8)] as const),
  ];
  let primary = 0;
  formatPositions.forEach(([col, row], i) => {
    primary |= bitAt(modules, col, row) << i;
  });
  let secondary = 0;
  secondaryPositions.forEach(([col, row], i) => {
    secondary |= bitAt(modules, col, row) << i;
  });
  assert.equal(primary, secondary, '两份格式信息不一致');

  const formatBits = primary ^ 0x5412;
  const formatData = formatBits >>> 10;
  const formatRemainder = formatBits & 0x3ff;
  assert.equal(bchRemainder(formatData, 10, 0x537), formatRemainder, '格式信息 BCH 校验失败');
  assert.equal(formatData >>> 3, 0b00, '纠错等级不是 M');
  const mask = formatData & 0b111;

  // 版本信息：v≥7 才有，两份一致且 BCH(18,6) 通过
  if (version >= 7) {
    let vBitsA = 0;
    let vBitsB = 0;
    for (let i = 0; i < 18; i += 1) {
      const a = size - 11 + (i % 3);
      const b = Math.floor(i / 3);
      vBitsA |= bitAt(modules, a, b) << i;
      vBitsB |= bitAt(modules, b, a) << i;
    }
    assert.equal(vBitsA, vBitsB, '两份版本信息不一致');
    assert.equal(vBitsA >>> 12, version, '版本信息里的版本号与矩阵尺寸不符');
    assert.equal(
      bchRemainder(vBitsA >>> 12, 12, 0x1f25),
      vBitsA & 0xfff,
      '版本信息 BCH 校验失败',
    );
  }

  // 去掩码
  const maskFn = (row: number, col: number): boolean => {
    switch (mask) {
      case 0:
        return (row + col) % 2 === 0;
      case 1:
        return row % 2 === 0;
      case 2:
        return col % 3 === 0;
      case 3:
        return (row + col) % 3 === 0;
      case 4:
        return (Math.floor(row / 2) + Math.floor(col / 3)) % 2 === 0;
      case 5:
        return ((row * col) % 2) + ((row * col) % 3) === 0;
      case 6:
        return (((row * col) % 2) + ((row * col) % 3)) % 2 === 0;
      default:
        return (((row + col) % 2) + ((row * col) % 3)) % 2 === 0;
    }
  };
  const reserved = buildReserved(version);
  const unmasked = modules.map((row, rowIndex) =>
    row.map((dark, colIndex) =>
      reserved[rowIndex]?.[colIndex] === true ? dark : dark !== maskFn(rowIndex, colIndex),
    ),
  );

  // 按蛇形路径读码字
  const total = codewordCount(version);
  const codewords = new Array<number>(total).fill(0);
  let bitIndex = 0;
  for (let right = size - 1; right >= 1; right -= 2) {
    if (right === 6) right = 5;
    const upward = ((right + 1) & 2) === 0;
    for (let vertical = 0; vertical < size; vertical += 1) {
      const row = upward ? size - 1 - vertical : vertical;
      for (let offset = 0; offset < 2; offset += 1) {
        const col = right - offset;
        if (reserved[row]?.[col] === true) continue;
        const bit = bitAt(unmasked, col, row);
        if (bitIndex >= total * 8) {
          assert.equal(bit, 0, '余数位（remainder bits）必须为 0');
          continue;
        }
        if (bit === 1) codewords[bitIndex >>> 3] = codewords[bitIndex >>> 3]! | (1 << (7 - (bitIndex & 7)));
        bitIndex += 1;
      }
    }
  }
  assert.equal(bitIndex, total * 8, '数据区模块数与码字数不匹配');

  // 拆块 + 校验每块的 Reed-Solomon 码字（所有伴随式必须为 0）
  const plans: { data: number; ec: number }[] = [];
  for (const group of blockPlan(version)) {
    for (let i = 0; i < group.count; i += 1) plans.push({ data: group.data, ec: group.ec });
  }
  const blocks = plans.map(() => ({ data: [] as number[], ec: [] as number[] }));
  let cursor = 0;
  const maxData = Math.max(...plans.map((plan) => plan.data));
  for (let i = 0; i < maxData; i += 1) {
    for (const [index, plan] of plans.entries()) if (i < plan.data) blocks[index]!.data.push(codewords[cursor++]!);
  }
  const maxEc = Math.max(...plans.map((plan) => plan.ec));
  for (let i = 0; i < maxEc; i += 1) {
    for (const [index, plan] of plans.entries()) if (i < plan.ec) blocks[index]!.ec.push(codewords[cursor++]!);
  }
  assert.equal(cursor, total, '交织后的码字数量与分块表不符');

  for (const block of blocks) {
    const full = [...block.data, ...block.ec];
    for (let j = 0; j < block.ec.length; j += 1) {
      let syndrome = 0;
      for (const codeword of full) syndrome = gfMul(syndrome, GF_EXP[j]!) ^ codeword;
      assert.equal(syndrome, 0, `第 ${j} 个 RS 伴随式不为 0，纠错码字有误`);
    }
  }

  // 数据流：模式指示符 → 字符计数 → 字节 → 终止符 → 填充
  const stream: number[] = [];
  for (const block of blocks) for (const codeword of block.data) for (let i = 7; i >= 0; i -= 1) stream.push((codeword >>> i) & 1);
  const readBits = (start: number, length: number): number => {
    let value = 0;
    for (let i = 0; i < length; i += 1) value = (value << 1) | (stream[start + i] ?? 0);
    return value;
  };
  let position = 0;
  assert.equal(readBits(position, 4), 0b0100, '模式指示符不是 byte 模式');
  position += 4;
  const countWidth = version < 10 ? 8 : 16;
  const byteLength = readBits(position, countWidth);
  position += countWidth;
  const dataBytes: number[] = [];
  for (let i = 0; i < byteLength; i += 1) {
    dataBytes.push(readBits(position, 8));
    position += 8;
  }
  const terminator = Math.min(4, stream.length - position);
  for (let i = 0; i < terminator; i += 1) assert.equal(stream[position + i], 0, '终止符必须全 0');
  position += terminator;
  while (position % 8 !== 0) {
    assert.equal(stream[position], 0, '终止符之后的字节对齐位必须为 0');
    position += 1;
  }
  let pad = 0xec;
  while (position < stream.length) {
    assert.equal(readBits(position, 8), pad, '填充码字必须按 0xEC / 0x11 交替');
    pad = pad === 0xec ? 0x11 : 0xec;
    position += 8;
  }

  return { version, mask, dataBytes, ecBlocks: blocks.length };
}

/** 生成长度恰为 n 字节的确定内容（可打印 ASCII，避免退化重复）。 */
function asciiOfLength(n: number): string {
  return Array.from({ length: n }, (_, i) => String.fromCharCode(33 + ((i * 37) % 90))).join('');
}

